export function bookIdFromZefaniaNumber(bookNumber: number): string | undefined {
  if (!Number.isFinite(bookNumber) || bookNumber < 1 || bookNumber > bibleBookIdsInOrder.length) {
    return undefined
  }
  return bibleBookIdsInOrder[bookNumber - 1]
}

